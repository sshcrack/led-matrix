#!/usr/bin/env python3
"""Write the 3D models that the stock KiCad libraries reference but never shipped.

KiCad 9's footprint libraries point at a few ``.step`` files that are absent from the
kicad-packages3D release (checked against packages3D master, not just the installed package):
the JST VH side-entry connectors, the Molex Mini-Fit Jr 5569-04A2 header, the Littelfuse NANO2
fuse, and the TI RDF0022A / RPW0010A packages this board uses.  The 3D viewer and the STEP
export therefore show bare pads there.

This script writes one envelope box per part as VRML (mm, Z up, origin at the footprint origin,
the convention KiCad's own ``.wrl`` files use): x/y from the footprint's F.Fab outline, height
from the same table ``gen_envelope.py`` uses for the mechanical envelope.  They are fit and
visualisation stand-ins, not vendor geometry - swap in a vendor STEP when one is published.

``gen_lib.py`` and ``gen_pcb.py`` reference these files (``${KIPRJMOD}/lib/3dmodels``), so a
regenerated library and board keep them.

    python3 tools/gen_3dmodels.py
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from gen_envelope import height_for  # noqa: E402
from sexpr import find, find_all, fmt_num, parse  # noqa: E402

BOARD_DIR = HERE.parent / "power-halo-board"
OUT = BOARD_DIR / "lib" / "3dmodels"
SYSFP = Path("/usr/share/kicad/footprints")

# moulded IC body, natural nylon connector housing, ceramic fuse body
BLACK = (0.13, 0.13, 0.14)
NYLON = (0.90, 0.90, 0.86)
CERAMIC = (0.30, 0.30, 0.31)

# (library, footprint, colour)
SPECS = [
    ("ledpanel", "TI_RDF0022A_B3QFN-22_6.5x7.5mm", BLACK),
    ("ledpanel", "TI_RPW0010A_VQFN-HR-10_2x2mm", BLACK),
    ("Connector_JST", "JST_VH_S2P-VH_1x02_P3.96mm_Horizontal", NYLON),
    ("Connector_JST", "JST_VH_S3P-VH_1x03_P3.96mm_Horizontal", NYLON),
    ("Connector_JST", "JST_VH_S4P-VH_1x04_P3.96mm_Horizontal", NYLON),
    ("Connector_Molex", "Molex_Mini-Fit_Jr_5569-04A2_2x02_P4.20mm_Horizontal", NYLON),
    ("Fuse", "Fuse_Littelfuse-NANO2-451_453", CERAMIC),
]

FAB_SHAPES = ("fp_line", "fp_rect", "fp_poly", "fp_circle", "fp_arc")


def model_path(name: str) -> str | None:
    """KiCad model reference for a footprint name, or None when the stock model is used."""
    return f"${{KIPRJMOD}}/lib/3dmodels/{name}.wrl" if any(name == s[1] for s in SPECS) else None


def _xy(node, key):
    child = find(node, key)
    if child is None:
        return None
    return float(child[1]), float(child[2])


def _shape_points(node):
    kind = node[0]
    if kind in ("fp_line", "fp_rect", "fp_arc"):
        pts = [_xy(node, "start"), _xy(node, "end")]
        mid = _xy(node, "mid")          # arcs: the mid point bounds the bulge
        if mid:
            pts.append(mid)
        return [p for p in pts if p]
    if kind == "fp_poly":
        pts = find(node, "pts") or []
        return [(float(p[1]), float(p[2])) for p in find_all(pts, "xy")]
    if kind == "fp_circle":
        c, e = _xy(node, "center"), _xy(node, "end")
        if not (c and e):
            return []
        r = ((c[0] - e[0]) ** 2 + (c[1] - e[1]) ** 2) ** 0.5
        return [(c[0] - r, c[1] - r), (c[0] + r, c[1] + r)]
    return []


def fab_bbox(footprint):
    """Bounding box of the F.Fab outline (the physical part, not the courtyard)."""
    pts = []
    for kind in FAB_SHAPES:
        for node in find_all(footprint, kind):
            if (find(node, "layer") or [None, ""])[1] != "F.Fab":
                continue
            pts += _shape_points(node)
    if not pts:
        raise SystemExit(f"{footprint[1]}: no F.Fab outline to size the model from")
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def footprint_path(lib: str, name: str) -> Path:
    base = BOARD_DIR / "lib" / "ledpanel.pretty" if lib == "ledpanel" else SYSFP / f"{lib}.pretty"
    return base / f"{name}.kicad_mod"


def vrml(name: str, cx: float, cy: float, sx: float, sy: float, h: float, colour) -> str:
    """VRML box.  KiCad reads ``.wrl`` models in inches (its own library files are), so every
    length is written in inches while the comment and the generator's table stay in mm."""
    def inch(v: float) -> str:
        return fmt_num(round(v / 2.54, 5))

    return (
        "#VRML V2.0 utf8\n"
        f"# power-halo-board envelope box for {name}\n"
        f"# body {fmt_num(round(sx, 2))} x {fmt_num(round(sy, 2))} x {fmt_num(round(h, 2))} mm,"
        " centred on the F.Fab outline, sitting on the board top face.\n"
        "# Generated by tools/gen_3dmodels.py: F.Fab outline x/y, gen_envelope height table for z.\n"
        "# Coordinates are inches (KiCad's VRML convention). Not vendor geometry - replace with\n"
        "# a vendor STEP when one is published.\n"
        "Transform {\n"
        f"  translation {inch(cx)} {inch(cy)} {inch(h / 2)}\n"
        "  children [\n"
        "    Shape {\n"
        "      appearance Appearance {\n"
        "        material Material {\n"
        f"          diffuseColor {colour[0]} {colour[1]} {colour[2]}\n"
        "          specularColor 0.2 0.2 0.2\n"
        "          shininess 0.2\n"
        "        }\n"
        "      }\n"
        f"      geometry Box {{ size {inch(sx)} {inch(sy)} {inch(h)} }}\n"
        "    }\n"
        "  ]\n"
        "}\n"
    )


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for lib, name, colour in SPECS:
        path = footprint_path(lib, name)
        if not path.exists():
            raise SystemExit(f"footprint {lib}:{name} not found at {path}")
        x1, y1, x2, y2 = fab_bbox(parse(path.read_text()))
        h, why = height_for(name)
        (OUT / f"{name}.wrl").write_text(
            vrml(name, (x1 + x2) / 2, (y1 + y2) / 2, x2 - x1, y2 - y1, h, colour))
        rows.append((name, x2 - x1, y2 - y1, h, why))
    width = max(len(r[0]) for r in rows)
    for name, sx, sy, h, why in rows:
        print(f"{name:<{width}}  {sx:5.2f} x {sy:5.2f} x {h:4.2f} mm  ({why})")
    print(f"{len(rows)} models -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
